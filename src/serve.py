class Handler(BaseHTTPRequestHandler):
    # Service worker registration refuses HTTP/1.0 responses, and BaseHTTP
    # defaults to 1.0. Every response below sends an accurate Content-Length,
    # which is what 1.1 keep-alive requires.
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):
        print(f"  {self.address_string()} {fmt % args}")

    @staticmethod
    def _finite(value):
        """Replaces NaN and infinities with null, recursively.

        pandas produces NaN for any missing cell, and Python's json.dumps
        writes that as a bare NaN token. Python reads it back happily, so the
        problem is invisible from here -- but NaN is not valid JSON, and every
        strict parser rejects the whole document: Android's org.json,
        JavaScript's JSON.parse, Go, Swift. One empty location name was enough
        to make /api/risk unreadable to the mobile app.
        """
        if isinstance(value, float):
            return None if (value != value or value in (float("inf"), float("-inf"))) else value
        if isinstance(value, dict):
            return {k: Handler._finite(v) for k, v in value.items()}
        if isinstance(value, (list, tuple)):
            return [Handler._finite(v) for v in value]
        return value

    def _json(self, payload, status=200):
        body = json.dumps(self._finite(payload), default=str).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(body)

    def _html(self, path):
        if not os.path.exists(path):
            self._json(
                {
                    "error": "dashboard not built",
                    "fix": "run: python src/build_dashboard.py",
                },
                status=404,
            )
            return
        with open(path, "rb") as f:
            body = f.read()
        # The dashboard file is a fragment (no <html> wrapper) because it is
        # also published as an Artifact; wrap it for standalone browsing.
        page = b"<!doctype html><html><head></head><body>" + body + b"</body></html>"
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(page)))
        # The dashboard is regenerated by build_dashboard.py on every run. With
        # no cache directive the browser caches it heuristically and the service
        # worker then caches that, so a rebuilt dashboard can keep serving the
        # previous build until storage is cleared by hand.
        self.send_header("Cache-Control", "no-cache, must-revalidate")
        self.end_headers()
        self.wfile.write(page)

    def _static(self, route):
        rel = route[len("/static/") :]
        path = os.path.normpath(os.path.join(STATIC_DIR, rel))
        if not path.startswith(STATIC_DIR) or not os.path.exists(path):
            self._json({"error": "not found"}, status=404)
            return
        ctype = mimetypes.guess_type(path)[0] or "application/octet-stream"
        with open(path, "rb") as f:
            body = f.read()
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        # The worker must be served from the root scope to control "/".
        if path.endswith("sw.js"):
            self.send_header("Service-Worker-Allowed", "/")
            self.send_header("Cache-Control", "no-cache")
        self.end_headers()
        self.wfile.write(body)

